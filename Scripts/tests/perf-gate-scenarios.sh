# make_gate <path> <fixture> <seconds|UNFROZEN> [summarizer]: perf-gate.sh
# sourced through its PERF_GATE_SOURCED hook with <fixture>'s deadline
# replaced (UNFROZEN: put back to TIMEOUT_UNFROZEN, so the refusal path for a
# fixture whose pilot has not run yet stays covered once every real fixture
# is frozen) and, optionally, another summarizer script.
make_gate() {
    local path="$1" fixture="$2" timeout="$3" summarizer="${4:-}"
    {
        printf '#!/usr/bin/env bash\n# generated by perf-gate-scenarios.sh\nPERF_GATE_SOURCED=1\n'
        printf '. %q\n' "$GATE"
        printf '_fixture=%q\n_timeout=%q\n_summarizer=%q\n' "$fixture" "$timeout" "$summarizer"
        cat <<'EOF'
[ "$_timeout" != "UNFROZEN" ] || _timeout="$TIMEOUT_UNFROZEN"
_timeouts=""
for _pair in $DEFAULT_TIMEOUTS; do
    case "$_pair" in "$_fixture"=*) _pair="$_fixture=$_timeout" ;; esac
    _timeouts="$_timeouts $_pair"
done
DEFAULT_TIMEOUTS="${_timeouts# }"
[ -z "$_summarizer" ] || SUMMARIZE_PY="$_summarizer"
main "$@"
EOF
    } > "$path"
    chmod +x "$path"
}

# make_summarizer <path> <python statements>: the real perf_summarize.py with
# design pr3 (`d`) changed by the statements before main() runs. The fake
# predecessor app is not the binary the design pins, so the pr3 scenarios run
# with the pin set to the fake's sha256; two scenarios keep the real pin or
# add a declaration the design must refuse.
make_summarizer() {
    local path="$1" patch="$2"
    {
        printf '#!/usr/bin/env python3\n# generated by perf-gate-scenarios.sh\n'
        printf 'import importlib.util\nimport sys\n\nsys.dont_write_bytecode = True\n'
        printf 'spec = importlib.util.spec_from_file_location("perf_summarize", %s)\n' \
            "$(python3 -I -c 'import json, sys; print(json.dumps(sys.argv[1]))' "$HERE/../perf_summarize.py")"
        printf 'mod = importlib.util.module_from_spec(spec)\nsys.modules["perf_summarize"] = mod\n'
        printf 'spec.loader.exec_module(mod)\nd = mod.DESIGNS["pr3"]\n%s\nsys.exit(mod.main())\n' "$patch"
    } > "$path"
}

