# expect <name> <want exit> <grep pattern in output or -> -- <env...> -- <perf-gate args...>
# EXPECT_GATE=<script> expect … runs that script instead of perf-gate.sh.
expect() {
    local name="$1" want="$2" pattern="$3"; shift 3
    local -a envs=()
    if [ "${1:-}" = "--" ]; then
        shift
        while [ "$#" -gt 0 ] && [ "$1" != "--" ]; do envs+=("$1"); shift; done
        shift
    fi
    if [ "${#SELECTED[@]}" -gt 0 ] && ! printf '%s\n' "${SELECTED[@]}" | grep -qx "$name"; then return; fi
    rm -rf "$WORK/$name" "$WORK/sim-$name"
    env FAKE_SIM_ROOT="$WORK/sim-$name" ${envs[@]+"${envs[@]}"} "${EXPECT_GATE:-$GATE}" "$@" --out "$WORK/$name" \
        > "$WORK/$name.out" 2>&1
    local got=$?
    TOTAL=$((TOTAL + 1))
    if [ "$got" -eq "$want" ] && { [ "$pattern" = "-" ] || grep -q -- "$pattern" "$WORK/$name.out"; }; then
        PASSED=$((PASSED + 1)); printf 'ok   %s: exit %s\n' "$name" "$got"
    else
        printf 'FAIL %s: exit %s (want %s, pattern %s)\n' "$name" "$got" "$want" "$pattern"
        tail -5 "$WORK/$name.out" | sed 's/^/     /'
    fi
}
# expect_file <scenario> <file in its directory> <grep pattern>: one more
# check on a scenario's own output (counted when the scenario is selected).
expect_file() {
    local name="$1" file="$2" pattern="$3"
    if [ "${#SELECTED[@]}" -gt 0 ] && ! printf '%s\n' "${SELECTED[@]}" | grep -qx "$name"; then return; fi
    TOTAL=$((TOTAL + 1))
    if grep -qF -- "$pattern" "$WORK/$name/$file" 2>/dev/null; then
        PASSED=$((PASSED + 1)); printf 'ok   %s: %s has "%s"\n' "$name" "$file" "$pattern"
    else
        printf 'FAIL %s: %s lacks "%s"\n' "$name" "$file" "$pattern"
    fi
}
