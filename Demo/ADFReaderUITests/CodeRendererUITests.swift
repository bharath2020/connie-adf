    // MARK: 1. Copy

    /// Copy puts the block's exact code on the pasteboard, under both
    /// renderers: one short line, eight indented lines, and a block with a
    /// trailing newline (the expected strings are the generator's
    /// literals, not read back from the screen). The pasteboard is read on
    /// the host through the lifecycle agent (`HostAgent.pasteboard`); the
    /// copies run in an order in which each differs from the one before,
    /// and a sentinel is put there first (by the agent, or by the runner
    /// when `simctl pbcopy` does not take) and read back through the agent
    /// (the test fails before any tap when it is not there), so a Copy that
    /// wrote nothing cannot pass on stale content. Without the agent the test
    /// still taps every Copy and prints the `CODE_COPY …` lines, then
    /// skips: nothing was verified in the run.
    func testCopyPutsExactCodeOnPasteboard() throws {
        let agent = try? HostAgent.fromEnvironment()
        let blocks = [CodeUIParity.cp01, CodeUIParity.cp02, CodeUIParity.cp11]
        let sentinel = "ADF-CODE-COPY-SENTINEL"
        var sentinelSource = "the host agent (simctl pbcopy)"
        if let agent {
            // The sentinel must be on the pasteboard, read back, before the
            // first tap; otherwise the first Copy could pass on stale content.
            var sentinelProblem: String?
            do {
                try agent.setPasteboard(sentinel)
                var readBack = try agent.pasteboard()
                if readBack != sentinel {
                    // `simctl pbcopy` exits 0 and leaves the device
                    // pasteboard unchanged on this host's iOS 26.3
                    // simulators (Nov 2026), so the runner writes the
                    // sentinel itself; it never reads `UIPasteboard`.
                    sentinelSource = "the UI-test runner (simctl pbcopy left \(readBack.utf8.count) UTF-8 bytes unchanged)"
                    UIPasteboard.general.string = sentinel
                    readBack = try agent.pasteboard()
                }
                if readBack != sentinel {
                    sentinelProblem = "the pasteboard holds \(readBack.debugDescription.prefix(80)) after the sentinel was set"
                }
            } catch {
                sentinelProblem = "the host agent could not set or read back a pasteboard sentinel: \(error)"
            }
            if let sentinelProblem {
                try agent.record("Code Copy puts the exact code on the pasteboard (code-parity)", pass: false, [
                    "copies": [[String: Any]](), "mismatches": [String](), "sentinel_set_first": false,
                    "sentinel_problem": sentinelProblem,
                ])
                XCTFail("no Copy was checked: \(sentinelProblem)")
                return
            }
        }
        var copies: [[String: Any]] = []
        var mismatches: [String] = []
        var lastMarker = ""
        for textKit2 in [false, true] {
            let arm = textKit2 ? "textkit2" : "swiftui"
            let driver = launch(textKit2: textKit2)
            for block in blocks {
                let code = try XCTUnwrap(block.code, "\(block.name) has no literal code")
                XCTAssertTrue(driver.show(block), "\(block.name) never came into view (\(arm))")
                expectEngine(driver, block, textKit2: textKit2, "before Copy")
                XCTAssertTrue(driver.tapCopy(block), "no Copy button to tap above \(block.name) (\(arm))")
                lastMarker = codeUICopyMarker(block, arm: arm, expected: code, source: "fixture")
                var entry: [String: Any] = [
                    "block": block.owner, "label": block.name, "arm": arm, "expected_utf16": code.utf16.count,
                ]
                if let agent {
                    let pasted = try agent.pasteboard()
                    let exact = pasted == code
                    entry["pasteboard_utf16"] = pasted.utf16.count
                    entry["exact"] = exact
                    if !exact {
                        mismatches.append("\(block.name) (\(arm)): the pasteboard holds "
                            + "\(pasted.debugDescription.prefix(160)), expected \(code.debugDescription.prefix(160))")
                    }
                }
                copies.append(entry)
            }
            codeUIAttach(driver.app, "copy-\(arm)")
            driver.app.terminate()
        }
        // The last Copy is what the device pasteboard holds after the test.
        print("CODE_COPY_LAST \(lastMarker)")
        guard let agent else {
            throw XCTSkip("Copy was tapped for \(copies.count) blocks but the pasteboard was not read: "
                + "ADF_LIFECYCLE_DIR is not set. Run through Scripts/lifecycle-gate.sh --only "
                + "CodeRendererUITests/testCopyPutsExactCodeOnPasteboard, or compare `xcrun simctl pbpaste` "
                + "with the CODE_COPY_LAST line.")
        }
        try agent.record("Code Copy puts the exact code on the pasteboard (code-parity)", pass: mismatches.isEmpty, [
            "copies": copies, "mismatches": mismatches, "sentinel_set_first": true, "sentinel_set_by": sentinelSource,
            "read_with": "host agent request '\(HostAgent.pasteboardReadKind)' (xcrun simctl pbpaste)",
        ])
        XCTAssertTrue(mismatches.isEmpty, mismatches.joined(separator: "; "))
    }

    // MARK: 2. Horizontal pan, vertical drag

    /// A horizontal pan on the code moves it by the pan distance, and a
    /// vertical drag that starts on the code scrolls the document. Each
    /// arm, from rest in its own launch, pans the wide block twice (100 pt
    /// and 180 pt of finger travel). A scroll view starts moving only after
    /// a few points of travel, the same few for every pan, so the gated
    /// figures are: the two displacements differ by the two travels'
    /// difference within 2 px (the code follows the finger point for
    /// point); each displacement is the same in both arms within 2 px; and
    /// no pan loses more than `panSlop` to that start. Neither pan moves
    /// the code vertically. Then a 150 pt vertical drag from the same code
    /// moves the block up at least 100 pt and leaves its horizontal offset
    /// alone.
    func testHorizontalPanMovesCodeAndVerticalDragScrollsDocument() throws {
        let block = CodeUIParity.cp03
        let travels: [CGFloat] = [100, 180]
        var moved: [Bool: [CGFloat]] = [:]
        var scrolled: [Bool: CGFloat] = [:]
        var scale: CGFloat = 1
        for textKit2 in [false, true] {
            let arm = textKit2 ? "TextKit 2" : "SwiftUI"
            let driver = launch(textKit2: textKit2)
            let reader = driver.reader
            XCTAssertTrue(driver.show(block, minimum: 40), "\(block.name) never came into view (\(arm))")
            expectEngine(driver, block, textKit2: textKit2, "before the pans")
            scale = reader.pixelScale()
            let text = driver.text(block)
            var displacements: [CGFloat] = []
            for travel in travels {
                let before = text.frame
                let start = try XCTUnwrap(reader.panStart(onCodeText: before), "\(block.name) has no pan start on screen")
                reader.pan(from: start, by: travel)
                driver.pause(0.8)
                let after = text.frame
                displacements.append(before.minX - after.minX)
                codeUINote(String(format: "%@: finger %.0f pt, code moved %.2f pt sideways, %.2f pt vertically",
                                  arm, travel, before.minX - after.minX, after.minY - before.minY))
                XCTAssertLessThanOrEqual(abs(after.minY - before.minY) * scale, Self.shiftLimit,
                                         "\(arm): a horizontal pan moved the code vertically")
            }
            moved[textKit2] = displacements
            expectEngine(driver, block, textKit2: textKit2, "after the pans")
            codeUIAttach(driver.app, "pan-\(textKit2 ? "textkit2" : "swiftui")")

            let before = text.frame
            let onCode = try XCTUnwrap(reader.panStart(onCodeText: before), "\(block.name) has no drag start on screen")
            driver.dragVertically(from: CGPoint(x: reader.viewport.midX, y: onCode.y), by: 150)
            driver.pause(0.8)
            XCTAssertTrue(text.exists, "\(arm): \(block.name) left the tree after a 150 pt vertical drag")
            let after = text.frame
            scrolled[textKit2] = before.minY - after.minY
            codeUINote(String(format: "%@: vertical drag from the code moved the block up %.2f pt, sideways %.2f pt",
                              arm, before.minY - after.minY, after.minX - before.minX))
            XCTAssertLessThanOrEqual(abs(after.minX - before.minX) * scale, Self.shiftLimit,
                                     "\(arm): a vertical drag moved the code sideways")
            codeUIAttach(driver.app, "vertical-drag-\(textKit2 ? "textkit2" : "swiftui")")
            driver.app.terminate()
        }

        let swiftUI = try XCTUnwrap(moved[false]), textKit2 = try XCTUnwrap(moved[true])
        for (arm, displacements) in [("SwiftUI", swiftUI), ("TextKit 2", textKit2)] {
            XCTAssertEqual(displacements.count, travels.count, "\(arm): a pan was not measured")
            guard displacements.count == travels.count else { continue }
            let difference = (displacements[1] - displacements[0]) - (travels[1] - travels[0])
            XCTAssertLessThanOrEqual(abs(difference) * scale, Self.shiftLimit,
                                     "\(arm): pans of \(travels) pt moved the code \(displacements) pt: not point for point")
            for (travel, displacement) in zip(travels, displacements) {
                let lost = travel - displacement
                XCTAssertTrue(lost >= -1 && lost <= Self.panSlop,
                              "\(arm): a \(travel) pt pan moved the code \(displacement) pt")
            }
        }
        for index in travels.indices where index < swiftUI.count && index < textKit2.count {
            XCTAssertLessThanOrEqual(abs(textKit2[index] - swiftUI[index]) * scale, Self.shiftLimit,
                                     "a \(travels[index]) pt pan moved the code \(textKit2[index]) pt under TextKit 2, "
                                         + "\(swiftUI[index]) pt under SwiftUI")
        }
        for (arm, distance) in [("SwiftUI", scrolled[false] ?? 0), ("TextKit 2", scrolled[true] ?? 0)] {
            XCTAssertGreaterThanOrEqual(distance, 100, "\(arm): a 150 pt vertical drag that starts on the code "
                + "scrolled the document \(distance) pt")
        }
    }

    // MARK: 3. Search

    /// A search that matches inside a code block, in each arm. While it is
    /// active the block has no `tk2-row` (the TextKit 2 row paints no
    /// highlight, so the block draws as SwiftUI) and its neighbours keep
    /// theirs under TextKit 2; the highlight is on screen (amber pixels on
    /// the match's line, none there before the search or after it).
    /// Clearing the search brings the `tk2-row` back and moves no code
    /// text more than 2 px vertically.
    func testSearchInsideCodeFallsBackAndReturns() throws {
        let block = CodeUIParity.cp02
        let neighbours = [CodeUIParity.cp01, CodeUIParity.cp03]
        var highlighted: [String: Int] = [:]
        for textKit2 in [false, true] {
            let arm = textKit2 ? "TextKit 2" : "SwiftUI"
            let driver = launch(textKit2: textKit2)
            let reader = driver.reader
            XCTAssertTrue(driver.show(block), "\(block.name) never came into view (\(arm))")
            expectEngine(driver, block, textKit2: textKit2, "before the search")
            let text = driver.text(block)
            let idle = driver.highlightPixels(in: driver.firstLine(of: text.frame))

            let counter = driver.search(block.name)
            XCTAssertTrue(counter.hasPrefix("1 /"), "\(arm): \(block.name): counter \(counter)")
            XCTAssertTrue(reader.waitForDisappearance(of: driver.textKit2Row(owner: block.owner),
                                                      timeout: CodeUIDriver.engineTimeout),
                          "\(arm): the highlighted block \(block.owner) is still a TextKit 2 row")
            XCTAssertTrue(text.exists, "\(arm): the matched block is not in the tree")
            var neighboursChecked = 0
            for neighbour in neighbours where driver.isPartlyShown(driver.text(neighbour)) {
                neighboursChecked += 1
                if textKit2 {
                    XCTAssertTrue(driver.isTextKit2(neighbour),
                                  "neighbour \(neighbour.owner) left TextKit 2 (the search fallback is per block)")
                } else {
                    XCTAssertFalse(driver.textKit2Row(owner: neighbour.owner).exists, "a TextKit 2 row on SwiftUI")
                }
            }
            XCTAssertGreaterThan(neighboursChecked, 0, "\(arm): no neighbour of \(block.name) "
                + "(\(neighbours.map(\.name).joined(separator: ", "))) was on screen to check")
            let line = driver.firstLine(of: text.frame)
            let viewport = reader.viewport
            XCTAssertTrue(line.minY >= viewport.minY - 2 && line.maxY <= viewport.maxY + 2,
                          "\(arm): the match's line is not on screen (\(line) in \(viewport))")
            let active = driver.highlightPixels(in: line)
            highlighted[arm] = active
            codeUIAttach(driver.app, "search-active-\(textKit2 ? "textkit2" : "swiftui")")
            XCTAssertLessThanOrEqual(idle, Self.unhighlightedPixels,
                                     "\(arm): \(idle) highlight-coloured pixels on the line before any search")
            XCTAssertGreaterThanOrEqual(active, Self.highlightedPixels,
                                        "\(arm): no highlight visible on the match's line (\(active) pixels)")

            let scale = reader.pixelScale()
            let before = driver.tops([block] + neighbours)
            driver.clearSearch()
            // The engine first (under TextKit 2 the row returns), then the
            // tops, so a shift the swap back causes is measured.
            expectEngine(driver, block, textKit2: textKit2, "after clearing the search")
            let after = driver.tops([block] + neighbours)
            let shift = LabelShift(from: before, to: after, scale: scale)
            XCTAssertGreaterThan(shift.common, 0, "\(arm): no code text to compare across the clear")
            XCTAssertLessThanOrEqual(shift.maxPixels, Self.shiftLimit,
                                     "\(arm): clearing the search moved \(shift.worstLabel) \(shift.maxPixels) px")
            let cleared = driver.highlightPixels(in: driver.firstLine(of: text.frame))
            XCTAssertLessThanOrEqual(cleared, Self.unhighlightedPixels,
                                     "\(arm): \(cleared) highlight-coloured pixels left after clearing")
            codeUIAttach(driver.app, "search-cleared-\(textKit2 ? "textkit2" : "swiftui")")
            driver.app.terminate()
        }
        codeUINote("highlight-coloured pixels on the match's line while the search is active: \(highlighted)")
    }

