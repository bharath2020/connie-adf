    /// Launches code-parity on one renderer and waits for its first heading.
    private func launch(textKit2: Bool = false) -> CodeUIDriver {
        let driver = CodeUIDriver(textKit2: textKit2)
        driver.reader.waitForRenderer(textKit2 ? "TextKit 2" : "SwiftUI")
