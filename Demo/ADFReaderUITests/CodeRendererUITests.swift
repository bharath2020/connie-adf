    private static let panTravel: CGFloat = 230
    private static let panHeld: CGFloat = 200
    private static let panSlop: CGFloat = 20
    private static let roundTrips = 5
    /// The least highlight-coloured pixels a visible match has (one
    /// five-character match covers thousands at 2x), and the most a block
    /// without a highlight may have.
    private static let highlightedPixels = 200
    private static let unhighlightedPixels = 20
    /// The residual `testLongPressShowsEditMenuOnSwiftUIOnly` pins: a
    /// TextKit 2 code row has no long-press selection yet. PR 8 adds it,
