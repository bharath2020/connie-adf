import UIKit
import XCTest

// Code-block interaction, accessibility and end-to-end UI tests for the
// TextKit 2 code renderer (PR 3 plan §5 "Interaction assertions", §3.0 E4
// and E5, §8), on `code-parity`.
//
// Which code is a TextKit 2 row under ON: the code text of a top-level code
// block whose content is eligible (`TextKit2Eligibility.codeVerdict`:
// printable ASCII and line feeds in a monospaced code font) and whose
// canvas bound is within the admission caps where it is drawn
// (`TextKit2Scope.codeGate`: 8,192 px per side and 16 MiB at the current
// Text Size, weight and display scale). The badge, the Copy button, the box
// and the horizontal scroll view are SwiftUI under either renderer. Code
// inside a list item, a panel or an expand stays SwiftUI.
//
// Owners. A code row is a `tk2-row:<owner>` element whose owner is the code
// block's `RenderBlock.id`, which for a top-level block is `0.<index>`: the
// same form as a top-level paragraph's. Its label is the whole code, as the
// SwiftUI text's is, so a block is found by how its code starts under
// either renderer, and its engine by the identifier.
//
// Geometry. A code text's frame is the text's natural size at the place the
// block's horizontal scroll view has put it, so `frame.minX` moves with a
// horizontal pan and `frame.width` is the scroll range plus the viewport.
// Positions are compared in device pixels (`ReaderDriver.pixelScale`).
//
// Pasteboard. A UI test must not read `UIPasteboard` (the cross-app paste
// prompt blocks the run). `testCopyPutsExactCodeOnPasteboard` asks the host
// agent (`HostAgent.pasteboard`, `xcrun simctl pbpaste` on the host) when
// `ADF_LIFECYCLE_DIR` is set (`Scripts/lifecycle-gate.sh --only
// CodeRendererUITests/testCopyPutsExactCodeOnPasteboard`); every Copy tap
// also prints a `CODE_COPY …` line carrying the expected text
// (`utf8_base64=`), which a runner without the agent can match against
// `xcrun simctl pbpaste` after the test.
//
// Driving helpers come from `ReaderDriver` (LifecycleSupport.swift); the
// code-specific ones below are private to this file.

// MARK: - Fixture facts

/// One code block of `Fixtures/code-parity.json` (generated by
/// `Tools/make-fixtures.swift`, `makeCodeParity`).
private struct CodeUIBlock {
    /// The sentinel on its first non-empty line (`CP-<nn>`).
    let name: String
    /// `RenderBlock.id`: the owner its TextKit 2 row carries.
    let owner: String
    /// How its code starts: the start of its accessibility label under
    /// either renderer.
    let prefix: String
    /// The root heading above it (a Table of Contents entry).
    let section: String
    /// The whole code, where the generator states it literally.
    var code: String? = nil
}

