    // MARK: 6. Text Size

    /// Text Size step 0 → 3 moves the near-budget block to SwiftUI with the
    /// same height as the SwiftUI arm. CP-16 is sized to sit just under
    /// the canvas budget at step 0 on a 3x display, so the test skips at
    /// 2x, where it stays admitted. The SwiftUI arm measures the block's
    /// code text at steps 0 and 3; the TextKit 2 arm must draw it as a
    /// TextKit 2 row at step 0, as SwiftUI at step 3 (still on the
    /// TextKit 2 renderer) at the SwiftUI arm's step-3 height within 1 px,
    /// and as a TextKit 2 row again back at step 0.
    func testTextSizeStepMovesNearBudgetBlockToSwiftUI() throws {
        let block = CodeUIParity.cp16
        var heights: [Bool: [Int: CGFloat]] = [:]
        var scale: CGFloat = 1
        for textKit2 in [false, true] {
            let arm = textKit2 ? "TextKit 2" : "SwiftUI"
            let driver = launch(textKit2: textKit2)
            let reader = driver.reader
            scale = reader.pixelScale()
            if scale < 2.5 {
                driver.app.terminate()
                throw XCTSkip("\(block.name) crosses the canvas budget at Text Size step 3 only on a 3x display; "
                    + "this one is \(scale)x, where it stays a TextKit 2 row")
            }
            XCTAssertTrue(driver.show(block, minimum: 60), "\(block.name) never came into view (\(arm))")
            expectEngine(driver, block, textKit2: textKit2, "step 0")
            let text = driver.text(block)
            var measured: [Int: CGFloat] = [0: text.frame.height]

            let larger = reader.stepTextSize(3)
            driver.pause(1.5)
            XCTAssertTrue(text.waitForExistence(timeout: 10), "\(arm): \(block.name) left the tree at step 3")
            measured[3] = text.frame.height
            if textKit2 {
                XCTAssertTrue(reader.isRenderer("TextKit 2", timeout: 2), "the renderer changed with the Text Size")
                XCTAssertFalse(driver.textKit2Row(owner: block.owner).exists,
                               "step 3: \(block.name) is still a TextKit 2 row, over the canvas budget")
                let others = try reader.documentSnapshot().textKit2Rows.keys.sorted()
                codeUINote("step 3: TextKit 2 rows still in the tree: \(others)")
            } else {
                XCTAssertFalse(reader.anyTextKit2Row.exists, "step 3: a TextKit 2 row exists on SwiftUI")
            }
            codeUIAttach(driver.app, "text-size-3-\(textKit2 ? "textkit2" : "swiftui")")

            let restored = reader.stepTextSize(-3)
            driver.pause(1.5)
            XCTAssertNotNil(larger, "\(arm): no Text Size readout")
            XCTAssertNotEqual(larger, "100%", "\(arm): the Text Size did not change")
            XCTAssertEqual(restored, "100%", "\(arm): the Text Size did not return to 100 %")
            XCTAssertTrue(text.waitForExistence(timeout: 10), "\(arm): \(block.name) left the tree back at step 0")
            expectEngine(driver, block, textKit2: textKit2, "back at step 0")
            XCTAssertLessThanOrEqual(abs(text.frame.height - (measured[0] ?? 0)) * scale, 1.01,
                                     "\(arm): \(block.name) did not return to its step-0 height")
            heights[textKit2] = measured
            driver.app.terminate()
        }
        let swiftUI = try XCTUnwrap(heights[false]), textKit2 = try XCTUnwrap(heights[true])
        let swiftUI3 = try XCTUnwrap(swiftUI[3]), textKit23 = try XCTUnwrap(textKit2[3])
        let swiftUI0 = try XCTUnwrap(swiftUI[0]), textKit20 = try XCTUnwrap(textKit2[0])
        codeUINote(String(format: "%@ code text height: step 0 SwiftUI %.2f pt, TextKit 2 %.2f pt; "
                + "step 3 SwiftUI %.2f pt, TextKit 2 arm %.2f pt", block.name, swiftUI0, textKit20, swiftUI3, textKit23))
        XCTAssertGreaterThan(swiftUI3, swiftUI0 + 1, "the Text Size step did not enlarge the code")
        XCTAssertLessThanOrEqual(abs(textKit23 - swiftUI3) * scale, 1.01,
                                 "step 3: \(block.name) is \(textKit23) pt tall in the TextKit 2 arm, \(swiftUI3) pt on SwiftUI")
    }

    // MARK: Accessibility (E5)

    /// The accessibility tree of the same screen under both renderers, at
    /// the three sections of printable-ASCII code: the same elements,
    /// types, labels, values and order (each tree's inner band must be an
    /// ordered subsequence of the other's outer band, as rows may shift
    /// ≤ 2 px on a switch). A code block reads badge, "Copy code" button,
    /// code; the code is one element whose label is the whole text under
    /// either renderer. Both trees and their differences are attached.
    /// XCUITest shows type, label, value and frame, not traits or custom
    /// actions: speech is `testVoiceOverTraversalOfCodeBlock`'s.
    func testCodeAccessibilityTreeMatchesSwiftUI() throws {
        let driver = launch()
        let reader = driver.reader
        for section in [CodeUIParity.s1, CodeUIParity.s2, CodeUIParity.s3] {
            try codeUIStep("Accessibility tree at \(section)") {
                // No settling drag at the first section: the document is at
                // its top there (no jump to re-pin), and the pinned blocks
                // below it must stay fully in view.
                driver.jump(toHeading: section, settleDrag: section == CodeUIParity.s1 ? 0 : 60)
                driver.pause(1)
                let swiftUI = try reader.documentSnapshot()
                reader.chooseRenderer(textKit2: true)
                driver.pause(1.5)
                let textKit2 = try reader.documentSnapshot()
                let name = section.prefix(5)
                codeUIAttach(text: CodeUITree.render(CodeUITree.band(swiftUI, inset: 0)), "ax-\(name)-swiftui")
                codeUIAttach(text: CodeUITree.render(CodeUITree.band(textKit2, inset: 0)), "ax-\(name)-textkit2")
                XCTAssertTrue(swiftUI.textKit2Rows.isEmpty, "\(section): a TextKit 2 row exists on SwiftUI")
                XCTAssertGreaterThan(textKit2.codeOwnedRows, 0, "\(section): no TextKit 2 code row")

                let keys = { (snapshot: DocumentSnapshot, inset: CGFloat) in
                    CodeUITree.band(snapshot, inset: inset).map(CodeUITree.key)
                }
                let missingInTextKit2 = CodeUITree.missing(keys(swiftUI, 8), from: keys(textKit2, -4))
                let missingInSwiftUI = CodeUITree.missing(keys(textKit2, 8), from: keys(swiftUI, -4))
                if !missingInTextKit2.isEmpty || !missingInSwiftUI.isEmpty {
                    codeUIAttach(text: "only SwiftUI:\n" + missingInTextKit2.joined(separator: "\n")
                        + "\n\nonly TextKit 2:\n" + missingInSwiftUI.joined(separator: "\n"), "ax-\(name)-diff")
                }
                XCTAssertEqual(missingInTextKit2, [], "\(section): SwiftUI elements missing or reordered under TextKit 2")
                XCTAssertEqual(missingInSwiftUI, [], "\(section): TextKit 2 elements missing or reordered under SwiftUI")

                // Each code row is one element inside its block's scroll
                // view, and SwiftUI lists the same text there once.
                let codeLabels = { (snapshot: DocumentSnapshot, inset: CGFloat) in
                    CodeUITree.band(snapshot, inset: inset).filter(\.inNestedScroll).map(\.label)
                }
                XCTAssertEqual(CodeUITree.missing(codeLabels(swiftUI, 8), from: codeLabels(textKit2, -4)), [],
                               "\(section): SwiftUI code texts missing from the TextKit 2 blocks' scroll views")
                XCTAssertEqual(CodeUITree.missing(codeLabels(textKit2, 8), from: codeLabels(swiftUI, -4)), [],
                               "\(section): TextKit 2 code texts missing from the SwiftUI blocks' scroll views")
                XCTAssertFalse(codeLabels(swiftUI, -4).isEmpty, "\(section): no code text in view")

                if section == CodeUIParity.s1 {
                    // The pinned blocks: between the code before it and its
                    // own code, a block exposes its badge, then Copy; its
                    // code is one element labelled with the whole text.
                    for (arm, snapshot) in [("SwiftUI", swiftUI), ("TextKit 2", textKit2)] {
                        let nodes = CodeUITree.band(snapshot, inset: -4)
                        for block in [CodeUIParity.cp01, CodeUIParity.cp02] {
                            let code = try XCTUnwrap(block.code, "\(block.name) has no literal code")
                            guard let at = nodes.firstIndex(where: { $0.label == code }) else {
                                XCTFail("\(arm): no element labelled with \(block.name)'s whole code")
                                continue
                            }
                            XCTAssertTrue(nodes[at].inNestedScroll, "\(arm): \(block.name)'s code is not in its scroll view")
                            let previous = nodes[..<at].lastIndex(where: { $0.inNestedScroll }) ?? -1
                            let header = nodes[(previous + 1) ..< at].map(\.label)
                            XCTAssertEqual(
                                CodeUITree.missing(["swift", ReaderDriver.Identifier.copyCodeLabel], from: header), [],
                                "\(arm): \(block.name) does not expose its badge, then its Copy button, before its code: \(header)"
                            )
                        }
                    }
                    XCTAssertEqual(textKit2.textKit2Rows[CodeUIParity.cp02.owner], CodeUIParity.cp02.code,
                                   "the TextKit 2 row's label is not the whole code")
                }
                reader.chooseRenderer(textKit2: false)
                driver.pause(1)
            }
        }
    }

    /// VoiceOver speech over the first code blocks (after the CP-S1 heading
    /// through CP-03's code) under both renderers, compared utterance by
    /// utterance with whitespace collapsed: the badge, the Copy button and
    /// the code are spoken in the same order with the same words. The
    /// heading itself is left out: its level is PR 2's pinned residual
    /// (`ListRendererUITests`). Needs `XCUIDevice.voiceOverService`
    /// (iOS 27.0); skips on older runtimes, where only a VoiceOver pass by
    /// hand can show this.
    func testVoiceOverTraversalOfCodeBlock() throws {
        guard #available(iOS 27.0, *) else {
            throw XCTSkip("VoiceOver automation (XCUIDevice.voiceOverService) needs an iOS 27 runtime; "
                + "this is iOS \(UIDevice.current.systemVersion). VoiceOver traversal of code stays a manual check here.")
        }
        let driver = launch()
        let voiceOver = XCUIDevice.shared.voiceOverService
        addTeardownBlock { @MainActor in
            if XCUIDevice.shared.voiceOverService.isEnabled { try? XCUIDevice.shared.voiceOverService.disable() }
        }

        /// Utterances after the CP-S1 heading, through CP-03's code.
        func traverse() throws -> [String] {
            try voiceOver.enable()
            defer { try? voiceOver.disable() }
            var spoken: [String] = []
            var started = false
            for _ in 0 ..< 60 {
                let utterance = try voiceOver.moveForward().utterance
                if started { spoken.append(utterance) }
                if !started, utterance.contains("CP-S1") { started = true }
                if started, utterance.contains(CodeUIParity.cp03.name) { break }
            }
            return spoken
        }
        func collapsed(_ utterance: String) -> String {
            utterance.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        }

        let swiftUI = try traverse()
        codeUIAttach(text: swiftUI.joined(separator: "\n"), "voiceover-swiftui")
        driver.reader.chooseRenderer(textKit2: true)
        driver.pause(1.5)
        XCTAssertTrue(driver.isTextKit2(CodeUIParity.cp02), "the code is not a TextKit 2 row")
        let textKit2 = try traverse()
        codeUIAttach(text: textKit2.joined(separator: "\n"), "voiceover-textkit2")
        driver.reader.chooseRenderer(textKit2: false)

        XCTAssertFalse(swiftUI.isEmpty, "VoiceOver never reached CP-S1")
        XCTAssertTrue(swiftUI.contains { $0.contains(CodeUIParity.cp03.name) }, "VoiceOver never reached CP-03's code")
        XCTAssertTrue(swiftUI.contains { $0.contains(CodeUIParity.cp02.name) }, "CP-02's code was not spoken")
        XCTAssertTrue(swiftUI.contains { $0.contains(ReaderDriver.Identifier.copyCodeLabel) },
                      "no Copy button was announced")
        // Utterances arrive cut at about 64 characters.
        XCTAssertEqual(textKit2.map(collapsed), swiftUI.map(collapsed),
                       "VoiceOver speaks the code blocks differently under TextKit 2")
    }

    // MARK: Horizontal offset (E4)

    /// E4's UI half. A wide block panned at least 200 pt keeps its offset
    /// within 2 px on each of ten switches (five round trips) and does not
    /// accumulate; the code is a TextKit 2 row at every ON. Then, in each
    /// arm's own launch: pan the block, scroll away until its row has left
    /// the tree (collapsed), come back, and read its offset. What SwiftUI
    /// does with the offset across a collapse is not asserted; the
    /// TextKit 2 arm must do the same within 2 px.
    func testHorizontalOffsetSurvivesSwitchesAndCollapsesLikeSwiftUI() throws {
        let block = CodeUIParity.cp03
        var scale: CGFloat = 1

        try codeUIStep("Five round trips with the block panned") {
            let driver = launch()
            let reader = driver.reader
            scale = reader.pixelScale()
            XCTAssertTrue(driver.show(block, minimum: 40), "\(block.name) never came into view")
            let text = driver.text(block)
            let rest = text.frame.minX
            let start = try XCTUnwrap(reader.panStart(onCodeText: text.frame), "\(block.name) has no pan start on screen")
            reader.pan(from: start, by: Self.panTravel)
            driver.pause()
            let origin = text.frame
            XCTAssertGreaterThanOrEqual(rest - origin.minX, Self.panHeld, "the pan moved the code \(rest - origin.minX) pt")
            var last = origin
            for trip in 1 ... Self.roundTrips {
                for (textKit2, name) in [(true, "TextKit 2"), (false, "SwiftUI")] {
                    reader.chooseRenderer(textKit2: textKit2)
                    driver.pause()
                    XCTAssertTrue(text.exists, "\(block.name) left the tree (trip \(trip), \(name))")
                    if textKit2 {
                        XCTAssertTrue(driver.isTextKit2(block), "\(block.name) is not a TextKit 2 row (trip \(trip))")
                    } else {
                        XCTAssertFalse(driver.textKit2Row(owner: block.owner).exists, "a TextKit 2 row on SwiftUI (trip \(trip))")
                    }
                    let now = text.frame
                    let dx = abs(now.minX - last.minX) * scale, dy = abs(now.minY - last.minY) * scale
                    codeUINote(String(format: "Trip %ld → %@: offset %.2f pt, |ΔX| %.2f px, |ΔY| %.2f px",
                                      trip, name, rest - now.minX, dx, dy))
                    XCTAssertLessThanOrEqual(dx, Self.shiftLimit, "the offset moved \(dx) px (trip \(trip), \(name))")
                    XCTAssertLessThanOrEqual(dy, Self.shiftLimit, "the block moved \(dy) px vertically (trip \(trip), \(name))")
                    last = now
                }
            }
            XCTAssertLessThanOrEqual(abs(last.minX - origin.minX) * scale, Self.shiftLimit,
                                     "the offset accumulated over \(Self.roundTrips) round trips")
            XCTAssertLessThanOrEqual(abs(last.minY - origin.minY) * scale, Self.shiftLimit,
                                     "the block drifted vertically over \(Self.roundTrips) round trips")
            codeUIAttach(driver.app, "offset-round-trips-done")
            driver.app.terminate()
        }

        var offsets: [Bool: (panned: CGFloat, returned: CGFloat)] = [:]
        for textKit2 in [false, true] {
            let arm = textKit2 ? "TextKit 2" : "SwiftUI"
            try codeUIStep("Collapse and return on \(arm)") {
                let driver = launch(textKit2: textKit2)
                let reader = driver.reader
                XCTAssertTrue(driver.show(block, minimum: 40), "\(block.name) never came into view (\(arm))")
                expectEngine(driver, block, textKit2: textKit2, "before the pan")
                let text = driver.text(block)
                let rest = text.frame.minX
                let start = try XCTUnwrap(reader.panStart(onCodeText: text.frame), "\(block.name) has no pan start on screen")
                reader.pan(from: start, by: Self.panTravel)
                driver.pause()
                let panned = rest - text.frame.minX
                XCTAssertGreaterThanOrEqual(panned, Self.panHeld, "\(arm): the pan moved the code \(panned) pt")

                // Away: the last section, then on until the row is gone.
                driver.jump(toHeading: CodeUIParity.s6, settleDrag: 0)
                var drags = 0
                while text.exists, drags < 12 {
                    reader.drag(by: 400)
                    driver.pause(0.4)
                    drags += 1
                }
                XCTAssertFalse(text.exists, "\(arm): \(block.name)'s row never left the tree at the end of the document, "
                    + "so no collapse was exercised")
                codeUIAttach(driver.app, "offset-away-\(textKit2 ? "textkit2" : "swiftui")")

                XCTAssertTrue(driver.show(block, minimum: 40), "\(arm): \(block.name) never came back into view")
                expectEngine(driver, block, textKit2: textKit2, "after the return")
                let returned = rest - text.frame.minX
                offsets[textKit2] = (panned, returned)
                codeUINote(String(format: "%@: offset %.2f pt after the pan, %.2f pt after a collapse and return",
                                  arm, panned, returned))
                codeUIAttach(driver.app, "offset-back-\(textKit2 ? "textkit2" : "swiftui")")
                driver.app.terminate()
            }
        }
        let swiftUI = try XCTUnwrap(offsets[false]), textKit2 = try XCTUnwrap(offsets[true])
        XCTAssertLessThanOrEqual(abs(textKit2.panned - swiftUI.panned) * scale, Self.shiftLimit,
                                 "the same pan gave \(textKit2.panned) pt under TextKit 2, \(swiftUI.panned) pt under SwiftUI")
        XCTAssertLessThanOrEqual(abs(textKit2.returned - swiftUI.returned) * scale, Self.shiftLimit,
                                 "after a collapse the offset is \(textKit2.returned) pt under TextKit 2 and "
                                     + "\(swiftUI.returned) pt under SwiftUI: arm C must behave as arm B")
    }

