// MARK: - Accessibility tree

/// What two renderers must agree on for one element of an accessibility
/// snapshot (`DocumentSnapshot.Node`): type, label and value, in snapshot
/// (reading) order. Identifier and frame are not compared.
private enum CodeUITree {
    static func name(of type: XCUIElement.ElementType) -> String {
        switch type {
        case .staticText: return "text"
        case .button: return "button"
        case .link: return "link"
        case .image: return "image"
        case .other: return "other"
        case .textView: return "textView"
        case .cell: return "cell"
        case .scrollView: return "scrollView"
        default: return "type\(type.rawValue)"
        }
    }

    static func key(_ node: DocumentSnapshot.Node) -> String {
        "\(name(of: node.type)) \"\(node.label)\"" + (node.value.isEmpty ? "" : " = \(node.value)")
    }

    /// The nodes fully inside the snapshot's viewport inset by `inset`
    /// points (negative grows it).
    static func band(_ snapshot: DocumentSnapshot, inset: CGFloat) -> [DocumentSnapshot.Node] {
        let band = snapshot.viewport.insetBy(dx: 0, dy: inset)
        return snapshot.all.filter { $0.frame.minY >= band.minY && $0.frame.maxY <= band.maxY }
    }

    /// Items of `inner` that are not an ordered subsequence of `outer`.
    static func missing(_ inner: [String], from outer: [String]) -> [String] {
        var missing: [String] = []
        var index = outer.startIndex
        for item in inner {
            if let found = outer[index...].firstIndex(of: item) {
                index = outer.index(after: found)
            } else {
                missing.append(item)
            }
        }
        return missing
    }

    /// One line per node: engine, whether it sits in a code block's scroll
    /// view, and its key with line breaks made visible.
    static func render(_ nodes: [DocumentSnapshot.Node]) -> String {
        nodes.map { node -> String in
            let engine = node.owner != nil ? "[tk2] " : "      "
            let place = node.inNestedScroll ? "[code] " : "       "
            return engine + place + key(node).replacingOccurrences(of: "\n", with: "⏎")
        }.joined(separator: "\n")
    }
}

// MARK: - Driver

/// What a sweep through part of the document saw (`CodeUIDriver.sweep`).
private struct CodeUISweep {
    /// Owner → label of every TextKit 2 row in any snapshot of the sweep.
    var rows: [String: String] = [:]
    /// Names of the blocks whose code had any part on screen at a stop.
    var onScreen: Set<String> = []
    var stops = 0
    var reachedEnd = false
}

/// Drives one launched ADFReader on code-parity: Table of Contents jumps,
/// code blocks, Copy, the edit menu, search and screen pixels. Wraps the
/// shared `ReaderDriver`.
@MainActor
private struct CodeUIDriver {
    let reader: ReaderDriver
    var app: XCUIApplication { reader.app }

    /// `-rendererReset` (start on SwiftUI unless `textKit2`) and
    /// `-fontSizeStep 0` (Text Size taps never persist).
    init(textKit2: Bool = false) {
        var arguments = ["-fixture", CodeUIParity.fixture, "-rendererReset", "-rendererStats", "-fontSizeStep", "0"]
        if textKit2 {
            arguments.append("-textkit2")
        }
        reader = ReaderDriver(launching: arguments)
    }

    func pause(_ seconds: TimeInterval = 1) {
        reader.pause(seconds)
    }

    // MARK: Elements

    /// `block`'s code text under either renderer.
    func text(_ block: CodeUIBlock) -> XCUIElement {
        reader.element(labelPrefix: block.prefix)
    }

    /// The TextKit 2 row whose owner is exactly `owner`.
    func textKit2Row(owner: String) -> XCUIElement {
        app.descendants(matching: .any)
            .matching(identifier: ReaderDriver.Identifier.textKit2RowPrefix + owner).firstMatch
    }

    /// How long a `tk2-row` may take to appear or leave the tree after an
    /// engine change (a switch, a search highlight, a clear). On a loaded
    /// host one accessibility query took 4 to 5 s, so a 5 s window held a
    /// single evaluation and failed with the row already in its new state.
    /// A wait returns as soon as the state is reached.
    static let engineTimeout: TimeInterval = 30

    /// Whether `block`'s code is drawn by a TextKit 2 row with its own
    /// owner and its own text.
    func isTextKit2(_ block: CodeUIBlock, timeout: TimeInterval = CodeUIDriver.engineTimeout) -> Bool {
        let row = textKit2Row(owner: block.owner)
        return row.waitForExistence(timeout: timeout) && row.label.hasPrefix(block.prefix)
    }

    /// Fully inside the viewport, give or take `slack` points.
    func isShown(_ element: XCUIElement, slack: CGFloat = 2) -> Bool {
        guard element.exists else { return false }
        let frame = element.frame
        let viewport = reader.viewport
        return frame.height > 0 && frame.minY >= viewport.minY - slack && frame.maxY <= viewport.maxY + slack
    }

    /// Any part of it inside the viewport.
    func isPartlyShown(_ element: XCUIElement) -> Bool {
        guard element.exists else { return false }
        let frame = element.frame
        let viewport = reader.viewport
        return frame.height > 0 && frame.maxY > viewport.minY && frame.minY < viewport.maxY
    }

    func waitUntilShown(_ element: XCUIElement, timeout: TimeInterval = 10) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        repeat {
            if isShown(element) { return true }
            pause(0.25)
        } while Date() < deadline
        return isShown(element)
    }

    /// Points of `element`'s height inside the band a gesture can use (the
    /// one `ReaderDriver.panStart` uses: from 8 pt below the viewport's top
    /// to 60 pt above its bottom); 0 when it is not in the tree.
    func heightOnScreen(_ element: XCUIElement) -> CGFloat {
        guard element.exists else { return 0 }
        let frame = element.frame
        let viewport = reader.viewport
        return max(0, min(frame.maxY, viewport.maxY - 60) - max(frame.minY, viewport.minY + 8))
    }

    /// Top edges (points) of the code texts of `blocks` that are in the
    /// tree, by block name.
    func tops(_ blocks: [CodeUIBlock]) -> [String: CGFloat] {
        var tops: [String: CGFloat] = [:]
        for block in blocks {
            let element = text(block)
            if element.exists { tops[block.name] = element.frame.minY }
        }
        return tops
    }

    // MARK: Navigation

    /// Jumps to a root heading through the toolbar's Table of Contents
    /// (items are indented by level, so the match is on the title's end),
    /// then makes a short held drag so the last scroll before any renderer
    /// switch is a gesture, not a jump (a switch straight after a jump
    /// re-pins the jump's anchor; see LifecycleUITests).
    func jump(toHeading title: String, settleDrag: CGFloat = 60) {
        let contents = app.buttons["Table of Contents"]
        XCTAssertTrue(contents.waitForExistence(timeout: 5), "Table of Contents control missing")
        contents.tap()
        let item = app.buttons.matching(NSPredicate(format: "label ENDSWITH %@", title)).firstMatch
        XCTAssertTrue(item.waitForExistence(timeout: 5), "\(title) is not in the Table of Contents")
        item.tap()
        pause(1.5)
        XCTAssertTrue(waitUntilShown(reader.element(labelled: title)), "\(title) did not come into view")
        if settleDrag != 0 {
            reader.drag(by: settleDrag)
            pause(0.8)
        }
    }

    /// Brings `block`'s code into view: at least `minimum` points of its
    /// height (all of it, when it is shorter) inside the gesture band.
    /// When it is not there already: a jump to its section's heading, a
    /// 40 pt settling drag, then 200 pt drags toward the end.
    func show(_ block: CodeUIBlock, minimum: CGFloat = 20) -> Bool {
        let element = text(block)
        func enough() -> Bool {
            guard element.exists else { return false }
            return heightOnScreen(element) >= min(minimum, element.frame.height) - 0.5
        }
        if enough() { return true }
        jump(toHeading: block.section, settleDrag: 40)
        var drags = 0
        while !enough(), drags < 16 {
            reader.drag(by: 200)
            pause(0.4)
            drags += 1
        }
        return enough()
    }

    /// Drags `step` points at a time (> 0 toward the end) until `element`
    /// is fully in view; `afterEachDrag` runs after every drag.
    func scroll(by step: CGFloat, until element: XCUIElement, maxDrags: Int, afterEachDrag: () -> Void = {}) -> Bool {
        var drags = 0
        while !isShown(element), drags < maxDrags {
            reader.drag(by: step)
            pause(0.4)
            afterEachDrag()
            drags += 1
        }
        return isShown(element)
    }

    /// A slow, held vertical drag that starts at `point` (screen points):
    /// `points` > 0 moves the finger up (the content toward its end).
    func dragVertically(from point: CGPoint, by points: CGFloat) {
        let origin = app.coordinate(withNormalizedOffset: .zero)
        let start = origin.withOffset(CGVector(dx: point.x, dy: point.y))
        let end = origin.withOffset(CGVector(dx: point.x, dy: point.y - points))
        start.press(forDuration: 0.05, thenDragTo: end, withVelocity: .slow, thenHoldForDuration: 0.3)
    }

    /// From the current viewport, 250 pt at a time until `last`'s code is
    /// fully in view (at most `maxDrags` drags), with one accessibility
    /// snapshot per stop: every TextKit 2 row seen, and which of `blocks`
    /// had code on screen.
    func sweep(_ blocks: [CodeUIBlock], until last: CodeUIBlock, maxDrags: Int = 30) throws -> CodeUISweep {
        var sweep = CodeUISweep()
        let end = text(last)
        var drags = 0
        while true {
            let snapshot = try reader.documentSnapshot()
            sweep.stops += 1
            sweep.rows.merge(snapshot.textKit2Rows) { first, _ in first }
            for node in snapshot.all where snapshot.isOnScreen(node) {
                for block in blocks where node.label.hasPrefix(block.prefix) {
                    sweep.onScreen.insert(block.name)
                }
            }
            if isShown(end) {
                sweep.reachedEnd = true
                break
            }
            guard drags < maxDrags else { break }
            reader.drag(by: 250)
            pause(0.4)
            drags += 1
        }
        return sweep
    }

    // MARK: Copy and the edit menu

    /// The Copy button of `block`: the "Copy code" button nearest above its
    /// code text (the header row sits right above the code).
    func copyButton(for block: CodeUIBlock) -> XCUIElement? {
        let element = text(block)
        guard element.exists else { return nil }
        let top = element.frame.minY
        let buttons = app.buttons.matching(
            NSPredicate(format: "label == %@", ReaderDriver.Identifier.copyCodeLabel)
        ).allElementsBoundByIndex
        var nearest: (button: XCUIElement, distance: CGFloat)?
        for button in buttons {
            let distance = top - button.frame.maxY
            if distance >= -4, distance < nearest?.distance ?? .infinity {
                nearest = (button, distance)
            }
        }
        return nearest?.button
    }

    /// Taps `block`'s Copy button, scrolling the header into reach first
    /// when it is under the navigation bar. False when there is no button
    /// to tap.
    func tapCopy(_ block: CodeUIBlock) -> Bool {
        var attempts = 0
        while attempts < 4 {
            if let button = copyButton(for: block), button.isHittable {
                button.tap()
                pause(0.5)
                return true
            }
            reader.drag(by: -120)
            pause(0.5)
            attempts += 1
        }
        return false
    }

    /// Elements labelled exactly "Copy": the edit menu's item. A code
    /// block's own button is labelled "Copy code".
    private var editMenuCopyItems: XCUIElementQuery {
        app.descendants(matching: .any).matching(NSPredicate(format: "label == %@", "Copy"))
    }

    /// Presses the first line of `block`'s code for 1.2 s and reports
    /// whether an edit menu came up within 3 s (a "Copy" item that was not
    /// there before). With `inside`, the press point (screen points) is
    /// first asserted to lie inside that element's frame and the viewport,
    /// so a missing menu can only mean the element showed none.
    func longPressShowsEditMenu(_ block: CodeUIBlock, inside target: XCUIElement? = nil) -> Bool {
        let before = editMenuCopyItems.count
        let frame = text(block).frame
        let press = CGPoint(x: frame.minX + 40, y: frame.minY + 10)
        if let target {
            let targetFrame = target.frame
            let viewport = reader.viewport
            XCTAssertTrue(target.exists && targetFrame.contains(press),
                          "the press point \(press) is not inside \(target.identifier)'s frame \(targetFrame)")
            XCTAssertTrue(viewport.contains(press), "the press point \(press) is outside the viewport \(viewport)")
        }
        let point = app.coordinate(withNormalizedOffset: .zero).withOffset(CGVector(dx: press.x, dy: press.y))
        point.press(forDuration: 1.2)
        let deadline = Date().addingTimeInterval(3)
        repeat {
            if editMenuCopyItems.count > before { return true }
            pause(0.25)
        } while Date() < deadline
        return false
    }

    /// Dismisses an edit menu (and the selection behind it) by tapping the
    /// navigation bar's leading part (the title, or the empty bar before
    /// it), up to three times. Not the bar's middle: that is the renderer
    /// menu control, and on iOS 18.5 the tap that closes the edit menu also
    /// reaches it and opens the renderer menu, so the next `chooseRenderer`
    /// tap closed that menu instead of opening it.
    func dismissEditMenu(leaving baseline: Int = 0) {
        var taps = 0
        while editMenuCopyItems.count > baseline, taps < 3 {
            app.navigationBars.firstMatch.coordinate(withNormalizedOffset: CGVector(dx: 0.1, dy: 0.5)).tap()
            pause(0.6)
            taps += 1
        }
    }

    /// How many "Copy" items the screen holds with no edit menu up.
    func editMenuBaseline() -> Int {
        editMenuCopyItems.count
    }

    // MARK: About This Build

    /// As `ListUIDriver`: on a loaded host the renderer menu can take over
    /// 10 s to open its items and the sheet as long to appear.
    static let aboutTimeout: TimeInterval = 30

    func openAbout() {
        reader.openRendererMenu()
        let about = app.descendants(matching: .any).matching(identifier: ReaderDriver.Identifier.about).firstMatch
        XCTAssertTrue(about.waitForExistence(timeout: Self.aboutTimeout), "About This Build… missing from the menu")
        about.tap()
        XCTAssertTrue(app.staticTexts[ReaderDriver.Identifier.buildVersion].waitForExistence(timeout: Self.aboutTimeout),
                      "About This Build did not open")
    }

    func closeAbout() {
        let done = app.buttons[ReaderDriver.Identifier.buildDone]
        XCTAssertTrue(done.waitForExistence(timeout: Self.aboutTimeout), "Done button missing")
        done.tap()
        XCTAssertTrue(reader.waitForDisappearance(
            of: app.staticTexts[ReaderDriver.Identifier.buildVersion], timeout: Self.aboutTimeout
        ), "About sheet did not dismiss")
        pause(0.5)
    }

    // MARK: Search

    /// Opens Find in Page if needed, runs `query` and returns the counter
    /// once the scan has finished ("current / total", or "0").
    func search(_ query: String) -> String {
        let field = app.textFields[ReaderDriver.Identifier.searchField]
        if !field.exists {
            app.buttons["Find in Page"].tap()
        }
        XCTAssertTrue(field.waitForExistence(timeout: 5), "search field missing")
        field.tap()
        if let current = field.value as? String, !current.isEmpty, current != "Find in page" {
            field.typeText(String(repeating: XCUIKeyboardKey.delete.rawValue, count: current.count))
        }
        field.typeText(query + "\n")
        let counter = app.staticTexts[ReaderDriver.Identifier.searchCounter]
        XCTAssertTrue(counter.waitForExistence(timeout: 10), "search counter missing for \(query)")
        pause(1.5)
        return counter.exists ? counter.label : "missing"
    }

    /// The search bar's Done: clears the search and closes the bar.
    func clearSearch() {
        let field = app.textFields[ReaderDriver.Identifier.searchField]
        XCTAssertTrue(field.exists, "no search to clear")
        let row = field.frame
        let done = app.buttons.matching(NSPredicate(format: "label == %@", "Done")).allElementsBoundByIndex
            .first { abs($0.frame.midY - row.midY) < 30 }
        XCTAssertNotNil(done, "the search bar's Done button is missing")
        done?.tap()
        XCTAssertTrue(reader.waitForDisappearance(of: field, timeout: 5), "the search bar did not close")
        pause(1)
    }

    // MARK: Screen pixels

    /// The first line of a code text with `frame`, as far as it is on
    /// screen (points).
    func firstLine(of frame: CGRect) -> CGRect {
        let viewport = reader.viewport
        let left = max(frame.minX, viewport.minX)
        let right = min(frame.maxX, viewport.maxX)
        return CGRect(x: left, y: frame.minY, width: max(0, right - left), height: min(frame.height, 26))
    }

    /// Screen pixels inside `rect` (points) in the colour of the current
    /// search match (`ADFTheme.searchCurrentHighlight`, a saturated amber:
    /// red 1.0, green 0.78, blue 0.16). Code text is one colour on a grey
    /// box, so only a painted highlight has such pixels. -1 when the
    /// screenshot cannot be read.
    func highlightPixels(in rect: CGRect) -> Int {
        guard let image = XCUIScreen.main.screenshot().image.cgImage else { return -1 }
        let window = app.windows.firstMatch.frame
        guard window.width > 0, rect.width > 0, rect.height > 0 else { return -1 }
        let scale = CGFloat(image.width) / window.width
        let crop = CGRect(x: rect.minX * scale, y: rect.minY * scale, width: rect.width * scale, height: rect.height * scale)
            .integral.intersection(CGRect(x: 0, y: 0, width: image.width, height: image.height))
        guard !crop.isEmpty, let part = image.cropping(to: crop) else { return -1 }
        let width = part.width, height = part.height
        guard width > 0, height > 0 else { return -1 }
        var pixels = [UInt8](repeating: 0, count: width * height * 4)
        let drawn = pixels.withUnsafeMutableBytes { buffer -> Bool in
            guard let context = CGContext(
                data: buffer.baseAddress, width: width, height: height, bitsPerComponent: 8, bytesPerRow: width * 4,
                space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
            ) else { return false }
            context.draw(part, in: CGRect(x: 0, y: 0, width: width, height: height))
            return true
        }
        guard drawn else { return -1 }
        var count = 0
        var index = 0
        while index + 2 < pixels.count {
            let red = Int(pixels[index]), green = Int(pixels[index + 1]), blue = Int(pixels[index + 2])
            if red >= 200, green >= 130, blue <= 130, red - blue >= 90, green - blue >= 40 {
                count += 1
            }
            index += 4
        }
        return count
    }
}

// MARK: - Test case helpers

@MainActor
private extension XCTestCase {
    func codeUIStep(_ name: String, _ body: () throws -> Void) throws {
        try XCTContext.runActivity(named: name) { _ in try body() }
    }

    func codeUINote(_ text: String) {
        XCTContext.runActivity(named: text) { _ in }
    }

    func codeUIAttach(_ app: XCUIApplication, _ name: String) {
        let attachment = XCTAttachment(screenshot: app.screenshot())
        attachment.name = name
        attachment.lifetime = .keepAlways
        add(attachment)
    }

    func codeUIAttach(text: String, _ name: String) {
        let attachment = XCTAttachment(string: text)
        attachment.name = name
        attachment.lifetime = .keepAlways
        add(attachment)
    }

    /// The line a host matches against `xcrun simctl pbpaste` after a Copy
    /// tap: the block, the arm and the text Copy must have written
    /// (`utf8_base64`, so line breaks and trailing newlines survive a log).
    /// `source` says where the expected text came from: `fixture` (the
    /// generator's literal) or `ax-label` (the code text's accessibility
    /// label, for a block whose text the generator draws at random).
    func codeUICopyMarker(_ block: CodeUIBlock, arm: String, expected: String, source: String) -> String {
        let marker = "CODE_COPY block=\(block.owner) label=\(block.name) arm=\(arm) source=\(source) "
            + "utf16=\(expected.utf16.count) utf8_base64=\(Data(expected.utf8).base64EncodedString())"
        print(marker)
        codeUINote(marker)
        return marker
    }
