@MainActor
private extension XCTestCase {
    func listUIStep(_ name: String, _ body: () throws -> Void) throws {
        try XCTContext.runActivity(named: name) { _ in try body() }
    }

    func listUINote(_ text: String) {
        XCTContext.runActivity(named: text) { _ in }
    }

    func listUIAttach(_ app: XCUIApplication, _ name: String) {
        let attachment = XCTAttachment(screenshot: app.screenshot())
        attachment.name = name
        attachment.lifetime = .keepAlways
        add(attachment)
    }

    func listUIAttach(text: String, _ name: String) {
        let attachment = XCTAttachment(string: text)
        attachment.name = name
        attachment.lifetime = .keepAlways
        add(attachment)
    }

    /// One task tap's probe delta: exactly one dispatch, of `id` with the
    /// new state `isDone`, and no URL.
    func listUIExpectDispatch(
        from before: ListUIProbe, to after: ListUIProbe, id: String, isDone: Bool, _ context: String
    ) {
        XCTAssertEqual(after.taskDispatches, before.taskDispatches + 1,
                       "\(context): expected exactly one task dispatch (\(before) → \(after))")
        XCTAssertEqual(after.taskLast, "\(id) \(isDone)", "\(context): wrong task id or new state dispatched")
        XCTAssertEqual(after.urlOpens, before.urlOpens, "\(context): a task tap opened a URL")
    }

    /// The checkboxes in view match `wanted` (a landscape viewport may not
    /// hold every task), `required` among them.
    func listUIExpectStates(_ states: [String: String], _ wanted: [String: String], required: String, _ context: String) {
        XCTAssertNotNil(states[required], "\(context): \(required) is not in view")
        XCTAssertGreaterThanOrEqual(states.count, 2, "\(context): fewer than two tasks in view: \(states)")
        for (owner, label) in states {
            XCTAssertEqual(label, wanted[owner], "\(context): task \(owner) changed")
        }
    }

    /// No dispatch and no URL between two probe reads.
    func listUIExpectNothing(from before: ListUIProbe, to after: ListUIProbe, _ context: String) {
        XCTAssertEqual(after.taskDispatches, before.taskDispatches, "\(context): dispatched a task toggle")
        XCTAssertEqual(after.urlOpens, before.urlOpens, "\(context): opened a URL")
    }
}

