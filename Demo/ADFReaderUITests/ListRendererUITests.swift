    /// One launch of `fixture`; every `ListUILinks` case in it.
    private func checkLinks(in fixture: String) throws {
        let driver = ListUIDriver(fixture: fixture)
        driver.reader.waitForRenderer("SwiftUI")
        let top = fixture == ListUIParity.fixture ? ListUIParity.s1 : ListUILinksFixture.s1
        XCTAssertTrue(driver.reader.element(labelled: top).waitForExistence(timeout: 15), "\(fixture) did not render")

        for link in ListUILinks.all where link.fixture == fixture {
            try listUIStep("Link \(link.url)") {
                driver.jump(toHeading: link.section)
                let leader = driver.element(link.row)
                XCTAssertTrue(driver.reveal(leader, below: link.section), "\(link.row.text) never came into view")
                driver.pause(0.5)
                let swiftUIFrame = leader.frame
                let (candidates, located) = driver.linkPoints(link, leader: leader)
                let blank = driver.whitespacePoint(textMaxX: swiftUIFrame.maxX, leader: leader)
                let describe = { (point: CGPoint) in String(format: "(%.1f, %.1f)", point.x, point.y) }
                listUINote("link points \(candidates.map(describe).joined(separator: ", ")) from "
                    + (located ? "the SwiftUI link element" : "the fallback estimate")
                    + ", whitespace \(describe(blank)), text maxX \(swiftUIFrame.maxX)")
                // The point TextKit 2 must open: the first candidate SwiftUI
                // opens. `Text` can miss a wrapped bidirectional run's glyphs
                // (the baseline's quirk, noted); when it opens at none,
                // TextKit 2 must open the exact URL at one of the same points.
                var linkPoint: CGPoint?

                for textKit2 in [false, true] {
                    let arm = textKit2 ? "TextKit 2" : "SwiftUI"
                    if textKit2 {
                        driver.reader.chooseRenderer(textKit2: true)
                        driver.pause(1.5)
                        XCTAssertTrue(driver.isTextKit2(link.row), "\(link.row.owner) is not a TextKit 2 row")
                        let shift = abs(leader.frame.minY - swiftUIFrame.minY) * driver.reader.pixelScale()
                        XCTAssertLessThanOrEqual(shift, Self.maxShiftPixels + 0.01,
                                                 "\(link.row.owner) moved \(shift) px on the switch; stale link point")
                        let backed = driver.aboutCount(ListUIProbe.Identifier.textKit1BackedRows, until: { $0 > 0 })
                        XCTAssertGreaterThan(backed ?? 0, 0,
                            "no TextKit 1-backed row is live with \(link.row.owner) in view")
                    }
                    let start = try XCTUnwrap(driver.readProbe())
                    var probe = start
                    var next = start
                    var opened: CGPoint?
                    let tries = textKit2 ? (linkPoint.map { [$0] } ?? candidates) : candidates
                    for point in tries {
                        driver.tap(at: point)
                        driver.pause(1.5)
                        XCTAssertEqual(driver.app.state, .runningForeground, "\(arm): the link left the app")
                        next = try XCTUnwrap(driver.readProbe())
                        if next.urlOpens != probe.urlOpens {
                            opened = point
                            break
                        }
                        listUINote("\(arm) opened nothing at \(describe(point)) on \(link.row.owner)")
                        probe = next
                    }
                    XCTAssertEqual(next.taskDispatches, start.taskDispatches, "\(arm): a link tap toggled a task")
                    if textKit2 {
                        XCTAssertNotNil(opened, "TextKit 2 opened nothing at "
                            + (linkPoint.map(describe) ?? candidates.map(describe).joined(separator: ", ")))
                    } else if opened == nil {
                        listUINote("baseline: SwiftUI Text opened \(link.url) at none of "
                            + candidates.map(describe).joined(separator: ", ")
                            + "; TextKit 2 must open it at one of them")
                    }
                    linkPoint = linkPoint ?? opened
                    if opened != nil {
                        XCTAssertEqual(next.urlOpens, probe.urlOpens + 1,
                            "\(arm): expected exactly one URL open (\(probe) → \(next))")
                        XCTAssertEqual(next.urlLast, link.url, "\(arm): the link routed the wrong URL")
                    }
                    listUIAttach(driver.app, "link-\(link.row.owner)-\(textKit2 ? "tk2" : "swiftui")")

                    probe = next
                    driver.tap(at: blank)
                    driver.pause(1)
                    next = try XCTUnwrap(driver.readProbe())
                    listUIExpectNothing(from: probe, to: next, "\(arm) whitespace beside \(link.row.owner)")

                    if !link.taskMarker {
                        probe = next
                        driver.tap(at: driver.markerPoint(leader: leader))
                        driver.pause(1)
                        next = try XCTUnwrap(driver.readProbe())
                        listUIExpectNothing(from: probe, to: next, "\(arm) marker of \(link.row.owner)")
                    } else {
                        // The checkbox toggles the task and never opens the link.
                        let box = try XCTUnwrap(driver.taskBox(leader: leader), "no checkbox on \(link.row.owner)")
                        let wasDone = box.label == "Completed task"
                        probe = next
                        box.tap()
                        driver.pause(1.5)
                        next = try XCTUnwrap(driver.readProbe())
                        listUIExpectDispatch(from: probe, to: next, id: link.row.owner, isDone: !wasDone, "\(arm) checkbox")
                        try XCTUnwrap(driver.taskBox(leader: leader), "checkbox vanished").tap()
                        driver.pause(1.5)
                        let restored = try XCTUnwrap(driver.readProbe())
                        listUIExpectDispatch(from: next, to: restored, id: link.row.owner, isDone: wasDone, "\(arm) restore")
                        next = restored
                    }
                }

                // A vertical fling that starts on the link (TextKit 2)
                // scrolls: toward the end only from lists-links' first
                // section (its second ends the document), else toward the
                // top. On lists-parity, momentum past LP-S5 would reach its
                // tables, where the baseline lazy stack livelocks (issue #8
                // class).
                let probe = try XCTUnwrap(driver.readProbe())
                let topBefore = leader.frame.minY
                let flingFrom = linkPoint ?? candidates[0]
                let start = driver.app.coordinate(withNormalizedOffset: .zero)
                    .withOffset(CGVector(dx: flingFrom.x, dy: flingFrom.y))
                let flingBy: CGFloat = link.section == ListUILinksFixture.s1 ? -260 : 260
                start.press(forDuration: 0.02, thenDragTo: start.withOffset(CGVector(dx: 0, dy: flingBy)),
                            withVelocity: .fast, thenHoldForDuration: 0)
                driver.pause(2)
                let moved = !leader.exists || abs(leader.frame.minY - topBefore) > 40
                XCTAssertTrue(moved, "a fling starting on \(link.row.owner)'s link did not scroll")
                let after = try XCTUnwrap(driver.readProbe())
                listUIExpectNothing(from: probe, to: after, "fling from \(link.row.owner)'s link")
                driver.reader.chooseRenderer(textKit2: false)
            }
        }
    }

    // MARK: Search

    /// Search under TextKit 2, on list-dense's text-only lists: a matched
    /// continuation paragraph or leader falls back to SwiftUI for that
    /// owner only (the row paints no highlight), its neighbours stay
    /// TextKit 2 rows with their own owners; an atom-bearing leader
    /// matches too and stays SwiftUI. The match survives Next match and
    /// switching both ways; clearing the search returns the eligible owner
    /// to TextKit 2.
    func testSearchFallsBackPerOwnerAndReturnsToTextKit2() throws {
        struct Case {
            let query: String
            let owner: ListUIRow
            /// The owner is eligible (TextKit 2 when no highlight).
            let eligible: Bool
            let neighbours: [ListUIRow]
        }
        // In document order (each is revealed by scrolling on); each query
        // matches once, so Next match stays on it.
        let cases = [
            Case(query: "block table stress", owner: ListUIDense.continuation3, eligible: true,
                 neighbours: [ListUIDense.leader3, ListUIDense.row3B, ListUIDense.row3C]),
            Case(query: "LD-004", owner: ListUIDense.leader4, eligible: true,
                 neighbours: [ListUIDense.row3C, ListUIDense.row4B]),
            Case(query: "LD-013", owner: ListUIDense.mentionTask, eligible: false,
                 neighbours: [ListUIDense.task13B, ListUIDense.task13C]),
        ]
        let driver = ListUIDriver(fixture: ListUIDense.fixture)
        driver.reader.waitForRenderer("SwiftUI")
        XCTAssertTrue(driver.element(ListUIDense.first).waitForExistence(timeout: 30), "list-dense missing")
        driver.reader.chooseRenderer(textKit2: true)
        driver.pause(1.5)

        for item in cases {
            try listUIStep("Search \(item.query) (owner \(item.owner.owner))") {
                let owner = driver.element(item.owner)
                XCTAssertTrue(driver.scrollDown(until: owner), "\(item.owner.text) never came into view")
                if item.eligible {
                    XCTAssertTrue(driver.isTextKit2(item.owner), "\(item.owner.owner) is not TextKit 2 before the search")
                } else {
                    XCTAssertFalse(driver.textKit2Row(owner: item.owner.owner).exists,
                        "atom owner \(item.owner.owner) is a TextKit 2 row")
                }
                let counter = driver.search(item.query)
                XCTAssertNotEqual(counter, "0", "\(item.query) found nothing")
                XCTAssertTrue(counter.hasPrefix("1 /"), "\(item.query): counter \(counter)")

                @MainActor func checkHighlighted(_ context: String, textKit2: Bool) {
                    XCTAssertTrue(driver.waitUntilShown(driver.element(item.owner)), "\(context): the match is not in view")
                    XCTAssertFalse(driver.textKit2Row(owner: item.owner.owner).exists,
                                   "\(context): the highlighted owner \(item.owner.owner) is still a TextKit 2 row")
                    for neighbour in item.neighbours where driver.isShown(driver.element(neighbour)) {
                        if textKit2 {
                            XCTAssertTrue(driver.isTextKit2(neighbour),
                                          "\(context): neighbour \(neighbour.owner) left TextKit 2 (fallback is per owner)")
                        } else {
                            XCTAssertFalse(driver.textKit2Row(owner: neighbour.owner).exists,
                                "\(context): TextKit 2 row on SwiftUI")
                        }
                    }
                }

                checkHighlighted("after the search", textKit2: true)
                listUIAttach(driver.app, "search-\(item.owner.owner)-tk2")
                driver.app.buttons["Next match"].tap()
                driver.pause(0.3)
                listUIAttach(driver.app, "search-\(item.owner.owner)-arrival-flash")
                driver.pause(1.2)
                checkHighlighted("after Next match", textKit2: true)
                driver.reader.chooseRenderer(textKit2: false)
                driver.pause(1.5)
                checkHighlighted("switched OFF", textKit2: false)
                driver.reader.chooseRenderer(textKit2: true)
                driver.pause(1.5)
                checkHighlighted("switched ON again", textKit2: true)
                XCTAssertEqual(driver.app.staticTexts[ReaderDriver.Identifier.searchCounter].label, counter,
                               "the switches changed the search counter")

                driver.clearSearch()
                if item.eligible {
                    XCTAssertTrue(driver.isTextKit2(item.owner),
                        "\(item.owner.owner) did not return to TextKit 2 after clearing")
                } else {
                    XCTAssertFalse(driver.textKit2Row(owner: item.owner.owner).exists, "atom owner became a TextKit 2 row")
                }
                for neighbour in item.neighbours where driver.isShown(driver.element(neighbour)) {
                    XCTAssertTrue(driver.isTextKit2(neighbour),
                        "neighbour \(neighbour.owner) is not TextKit 2 after clearing")
                }
                listUIAttach(driver.app, "search-\(item.owner.owner)-cleared")
            }
        }
        driver.reader.chooseRenderer(textKit2: false)
    }

