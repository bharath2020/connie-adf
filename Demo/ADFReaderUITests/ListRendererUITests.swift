import UIKit
import XCTest

// List interaction, accessibility and end-to-end UI tests for the TextKit 2
// list renderer (Astra §5 "Interaction assertions" and §8, Fable F18), on
// `lists-parity`, `lists-links` (linked list text), `list-dense` and
// `kitchen-sink`.
//
// Which rows must be TextKit 2. An assertion that a row is TextKit 2 under
// ON targets a single-block row (a leader alone, or a continuation
// paragraph after a nested list) in a list that holds only left-to-right
// text: leaders and plain paragraphs, no code, container, table, sync
// block, heading or sub/sup anywhere in the list. An assertion that a row
// stays SwiftUI under ON targets an atom-bearing leader or a column with a
// heading beside other text. Rows with a leader and trailing paragraphs,
// and lists-parity's LP-S4 list (it holds a code block), are asserted
// neither way while the rule for them is pending.
//
// Owners. A list row drawn by TextKit 2 is a `tk2-row:<owner>` element; a
// leader's owner is its `PreparedListRow.id` (the item's node path), a
// trailing paragraph's or heading's owner is its own `RenderBlock.id`. Task
// ids are those node paths too (`ListMarker.task(id:)`), never the JSON
// localId.
//
// Interaction probe. The demo surfaces a task toggle only as the checkbox's
// accessibility label and a persisted UserDefaults map, and hands links to
// the system (Safari). These tests launch with `-interactionProbe`
// (`InteractionProbe`, ReaderView.swift) and read About This Build instead:
// `probe-task-dispatches` (count) and `probe-task-last`
// ("<id> <true|false>") for `.taskToggled`, and `probe-url-opens` (count) and
// `probe-url-last` (absolute URL) for an `openURL` action that keeps link
// taps in the app. A missing hook fails the test that needs it, by name.
//
// Accessibility. XCUITest exposes element type, label, value, identifier and
// frame, not traits or custom actions, so the tree diff compares order,
// labels and marker exposure; heading semantics and link actions need
// VoiceOver speech. `testVoiceOverTraversalOfTasksAndDecisions` uses
// `XCUIDevice.voiceOverService` (iOS 27 runtimes only); on older runtimes it
// skips, and a VoiceOver pass by hand remains the evidence there.
//
// Driving helpers come from `ReaderDriver` (LifecycleSupport.swift); the
// list-specific ones below are private to this file.

