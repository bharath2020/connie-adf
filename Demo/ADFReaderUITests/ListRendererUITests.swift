// MARK: - Accessibility tree

/// One labelled element of an accessibility snapshot, in snapshot (reading)
/// order. `key` is what two renderers must agree on; identifier and frame
/// are not compared.
private struct ListUINode {
    let type: XCUIElement.ElementType
    let label: String
    let value: String
    let identifier: String
    let frame: CGRect

    var key: String {
        "\(Self.name(of: type)) \"\(label)\"" + (value.isEmpty ? "" : " = \(value)")
    }

    var isTextKit2Row: Bool { identifier.hasPrefix(ReaderDriver.Identifier.textKit2RowPrefix) }

    static func name(of type: XCUIElement.ElementType) -> String {
        switch type {
        case .staticText: return "text"
        case .button: return "button"
        case .link: return "link"
        case .image: return "image"
        case .other: return "other"
        case .textView: return "textView"
        case .cell: return "cell"
        case .scrollView: return "scrollView"
        default: return "type\(type.rawValue)"
        }
    }

    /// Items of `inner` that are not an ordered subsequence of `outer`.
    static func missing(_ inner: [String], from outer: [String]) -> [String] {
        var missing: [String] = []
        var index = outer.startIndex
        for item in inner {
            if let found = outer[index...].firstIndex(of: item) {
                index = outer.index(after: found)
            } else {
                missing.append(item)
            }
        }
        return missing
    }
}

/// One accessibility snapshot of the document's scroll view, flattened in
/// snapshot order (the order an element query's first match follows), and
/// the viewport (`ReaderDriver.viewport`) read with it. Answers the
/// queries a check would otherwise make one by one.
private struct ListUIScreen {
    let nodes: [ListUINode]
    let viewport: CGRect

    /// The first node `row` matches, as `ListUIDriver.element(_:)` finds it.
    func node(_ row: ListUIRow) -> ListUINode? {
        nodes.first { node in
            switch row.match {
            case .exact: return node.label == row.text
            case .prefix: return node.label.hasPrefix(row.text)
            case .contains: return node.label.contains(row.text)
            }
        }
    }

    /// `row`'s node when it is fully in view (`ListUIDriver.isShown`).
    func shown(_ row: ListUIRow, slack: CGFloat = 2) -> ListUINode? {
        guard let node = node(row) else { return nil }
        let viewport = viewport
        let frame = node.frame
        let inside = frame.height > 0 && frame.minY >= viewport.minY - slack && frame.maxY <= viewport.maxY + slack
        return inside ? node : nil
    }

    /// The task checkbox left of a leader and overlapping its first line.
    func taskBox(leaderFrame: CGRect) -> ListUINode? {
        marker(left: leaderFrame) { $0.type == .button && ($0.label == "Task" || $0.label == "Completed task") }
    }

    /// The "Decision" marker left of a leader and overlapping its first line.
    func decisionMarker(leaderFrame: CGRect) -> ListUINode? {
        marker(left: leaderFrame) { $0.label == "Decision" }
    }

    private func marker(left line: CGRect, where matches: (ListUINode) -> Bool) -> ListUINode? {
        let lineHeight = min(line.height, 40)
        return nodes.filter {
            matches($0) && $0.frame.maxX <= line.minX + 1 && $0.frame.maxY > line.minY
                && $0.frame.minY < line.minY + lineHeight
        }.min { abs($0.frame.midY - line.minY) < abs($1.frame.midY - line.minY) }
    }
}

/// A marker found in a snapshot: its label then, tapped at its centre.
@MainActor
private struct ListUIMarker {
    let label: String
    let frame: CGRect
    let app: XCUIApplication

    init(node: ListUINode, app: XCUIApplication) {
        label = node.label
        frame = node.frame
        self.app = app
    }

    func tap() {
        app.coordinate(withNormalizedOffset: .zero).withOffset(CGVector(dx: frame.midX, dy: frame.midY)).tap()
    }
}

// MARK: - Driver

/// Launches the reader on a list fixture and drives it: Table of Contents
/// jumps, list rows, task checkboxes, the probe, search, text size and
/// rotation. Wraps the shared `ReaderDriver`.
@MainActor
private struct ListUIDriver {
    let reader: ReaderDriver
    var app: XCUIApplication { reader.app }

    /// `-rendererReset` (start on SwiftUI), `-fontSizeStep 0` (Text Size
    /// taps never persist) and `-interactionProbe`. A `nil` fixture
    /// launches on the fixture list (`open(_:)`, `back()`).
    init(fixture: String?, extra: [String] = []) {
        reader = ReaderDriver(launching: (fixture.map { ["-fixture", $0] } ?? []) + [
            "-rendererReset", "-rendererStats", "-fontSizeStep", "0", "-interactionProbe",
        ] + extra)
    }

    /// From the fixture list, opens `fixture`.
    func open(_ fixture: String) {
        reader.openFixture(fixture)
    }

    /// Back from the reader to the fixture list.
    func back() {
        reader.goBack()
    }

    func pause(_ seconds: TimeInterval = 1) {
        reader.pause(seconds)
    }

    // MARK: Elements

    func element(_ row: ListUIRow) -> XCUIElement {
        switch row.match {
        case .exact: return reader.element(labelled: row.text)
        case .prefix: return reader.element(labelPrefix: row.text)
        case .contains:
            return app.descendants(matching: .any).matching(NSPredicate(format: "label CONTAINS %@", row.text))
                .firstMatch
        }
    }

    /// The TextKit 2 row whose owner is exactly `owner`.
    func textKit2Row(owner: String) -> XCUIElement {
        app.descendants(matching: .any)
            .matching(identifier: ReaderDriver.Identifier.textKit2RowPrefix + owner).firstMatch
    }

    /// Whether `row` is drawn by a TextKit 2 row with its own owner and its
    /// own text (no owner-ID substitution).
    func isTextKit2(_ row: ListUIRow, timeout: TimeInterval = 5) -> Bool {
        let drawn = textKit2Row(owner: row.owner)
        guard drawn.waitForExistence(timeout: timeout) else { return false }
        switch row.match {
        case .exact: return drawn.label == row.text
        case .prefix: return drawn.label.hasPrefix(row.text)
        case .contains: return drawn.label.contains(row.text)
        }
    }

    /// Fully inside the viewport, give or take `slack` points (a heading a
    /// Table of Contents jump pins to the top can sit a fraction above it).
    func isShown(_ element: XCUIElement, slack: CGFloat = 2) -> Bool {
        guard element.exists else { return false }
        let frame = element.frame
        let viewport = reader.viewport
        return frame.height > 0 && frame.minY >= viewport.minY - slack && frame.maxY <= viewport.maxY + slack
    }

    func waitUntilShown(_ element: XCUIElement, timeout: TimeInterval = 10) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        repeat {
            if isShown(element) { return true }
            pause(0.25)
        } while Date() < deadline
        return isShown(element)
    }

    // MARK: Navigation

    /// Jumps to a root heading through the toolbar's Table of Contents
    /// (items are indented with em spaces by level, so the match is on the
    /// title's end), then makes a short held drag so the last scroll before
    /// any renderer switch is a gesture, not a jump (a switch straight
    /// after a jump re-pins the jump's anchor; see LifecycleUITests).
    func jump(toHeading title: String, settleDrag: CGFloat = 60) {
        let contents = app.buttons["Table of Contents"]
        XCTAssertTrue(contents.waitForExistence(timeout: 5), "Table of Contents control missing")
        contents.tap()
        let item = app.buttons.matching(NSPredicate(format: "label ENDSWITH %@", title)).firstMatch
        XCTAssertTrue(item.waitForExistence(timeout: 5), "\(title) is not in the Table of Contents")
        item.tap()
        pause(1.5)
        XCTAssertTrue(waitUntilShown(reader.element(labelled: title)), "\(title) did not come into view")
        if settleDrag != 0 {
            reader.drag(by: settleDrag)
            pause(0.8)
        }
    }

    /// Jumps to `heading`, then drags down a little at a time until
    /// `element` is fully in view.
    func reveal(_ element: XCUIElement, below heading: String) -> Bool {
        if isShown(element) { return true }
        jump(toHeading: heading, settleDrag: 0)
        var drags = 0
        while !isShown(element), drags < 10 {
            reader.drag(by: 220)
            pause(0.4)
            drags += 1
        }
        return isShown(element)
    }

    /// Drags toward the end, a third of a screen at a time, until `element`
    /// is fully in view (for documents with no heading to jump to);
    /// `afterEachDrag` runs after every drag.
    func scrollDown(until element: XCUIElement, maxDrags: Int = 30, afterEachDrag: () -> Void = {}) -> Bool {
        scroll(by: 300, until: element, maxDrags: maxDrags, afterEachDrag: afterEachDrag)
    }

    /// `scrollDown(until:)` toward the top.
    func scrollUp(until element: XCUIElement, maxDrags: Int = 30, afterEachDrag: () -> Void = {}) -> Bool {
        scroll(by: -300, until: element, maxDrags: maxDrags, afterEachDrag: afterEachDrag)
    }

    private func scroll(by step: CGFloat, until element: XCUIElement, maxDrags: Int,
                        afterEachDrag: () -> Void) -> Bool {
        var drags = 0
        while !isShown(element), drags < maxDrags {
            reader.drag(by: step)
            pause(0.4)
            afterEachDrag()
            drags += 1
        }
        return isShown(element)
    }

    // MARK: Screen snapshot

    /// The whole app's accessibility tree, from one snapshot. Every
    /// marker, state and order check reads its frames here: one round trip
    /// in place of a query per element, which a loaded host turns into
    /// seconds each.
    func screen() -> ListUIScreen {
        var nodes: [ListUINode] = []
        func walk(_ node: XCUIElementSnapshot) {
            nodes.append(ListUINode(
                type: node.elementType, label: node.label, value: (node.value as? String) ?? "",
                identifier: node.identifier, frame: node.frame
            ))
            for child in node.children {
                walk(child)
            }
        }
        do {
            walk(try app.scrollViews.firstMatch.snapshot())
        } catch {
            XCTFail("accessibility snapshot of the document failed: \(error)")
        }
        return ListUIScreen(nodes: nodes, viewport: reader.viewport)
    }

    // MARK: Markers

    /// The task checkbox ("Task" / "Completed task") on the row whose leader
    /// is `leader`: left of the leader and overlapping its first line.
    func taskBox(leader: XCUIElement) -> ListUIMarker? {
        guard leader.exists else { return nil }
        return screen().taskBox(leaderFrame: leader.frame).map { ListUIMarker(node: $0, app: app) }
    }

    /// The "Decision" marker on the row whose leader is `leader`.
    func decisionMarker(leader: XCUIElement) -> ListUIMarker? {
        guard leader.exists else { return nil }
        return screen().decisionMarker(leaderFrame: leader.frame).map { ListUIMarker(node: $0, app: app) }
    }

    /// Checkbox label per task leader, for the tasks whose leader is in view.
    func taskStates(_ tasks: [ListUIRow]) -> [String: String] {
        let screen = screen()
        var states: [String: String] = [:]
        for task in tasks {
            guard let leader = screen.shown(task), let box = screen.taskBox(leaderFrame: leader.frame) else { continue }
            states[task.owner] = box.label
        }
        return states
    }

    /// Top edges of the rows in view, in document order: the order check.
    func tops(_ rows: [ListUIRow]) -> [(owner: String, top: CGFloat)] {
        let screen = screen()
        return rows.compactMap { row in
            screen.shown(row).map { (row.owner, $0.frame.minY) }
        }
    }

    static func inOrder(_ tops: [(owner: String, top: CGFloat)]) -> Bool {
        zip(tops, tops.dropFirst()).allSatisfy { $0.top < $1.top }
    }

    // MARK: Points

    func tap(at point: CGPoint) {
        app.coordinate(withNormalizedOffset: .zero).withOffset(CGVector(dx: point.x, dy: point.y)).tap()
    }

    /// Screen points on `link`'s glyphs in its text, best first, from the
    /// link element SwiftUI exposes inside the text when there is one: its
    /// centre for a one-line link. A link wrapped over two or more lines
    /// has a frame that is the union of its line spans, whose centre can
    /// fall between the lines, off the glyphs; for it, the start of its
    /// last line, then the end of its first line, a few points in from the
    /// paragraph's leading and trailing edges. Without an element:
    /// `linkCentre` along line `line`.
    func linkPoints(_ link: ListUILink, leader: XCUIElement) -> (points: [CGPoint], located: Bool) {
        let frame = leader.frame
        let lineHeight: CGFloat = 20.5
        let candidates = app.links.matching(NSPredicate(format: "label == %@", link.linkText)).allElementsBoundByIndex
        if let element = candidates.first(where: { $0.frame.intersects(frame) }) {
            // Clamped to the text's own frame: a bidirectional link's
            // element can report a frame wider than its glyphs.
            let span = element.frame.intersection(frame)
            guard span.height > lineHeight * 1.5 else { return ([CGPoint(x: span.midX, y: span.midY)], true) }
            let lastLine = span.maxY - lineHeight / 2
            let firstLine = span.minY + lineHeight / 2
            let edge = { (inset: CGFloat, leading: Bool) -> CGFloat in
                leading != link.rightToLeft ? span.minX + inset : span.maxX - inset
            }
            return ([
                CGPoint(x: edge(8, true), y: lastLine),
                CGPoint(x: edge(8, false), y: firstLine),
                CGPoint(x: edge(24, true), y: lastLine),
                CGPoint(x: edge(24, false), y: firstLine),
            ], true)
        }
        let y = min(frame.maxY - 2, frame.minY + (CGFloat(link.line) + 0.5) * lineHeight)
        return ([CGPoint(x: frame.minX + frame.width * link.linkCentre, y: y)], false)
    }

    /// Whitespace on the leader's line, right of its text (the SwiftUI text
    /// element hugs its glyphs; `textMaxX` is measured there).
    func whitespacePoint(textMaxX: CGFloat, leader: XCUIElement) -> CGPoint {
        let window = app.windows.firstMatch.frame
        let x = min(window.maxX - 12, max(textMaxX + 24, (textMaxX + window.maxX) / 2))
        return CGPoint(x: x, y: leader.frame.minY + min(leader.frame.height, 22) / 2)
    }

    /// The marker column left of the leader, on its first line.
    func markerPoint(leader: XCUIElement) -> CGPoint {
        CGPoint(x: leader.frame.minX - 18, y: leader.frame.minY + min(leader.frame.height, 22) / 2)
    }

    // MARK: About This Build

    /// About's waits. Xcode 27 evaluates every element query on the app's
    /// main thread, and on a loaded host one query can take seconds:
    /// ReaderDriver's 5 s waits, tuned on a quiet host, then fail an
    /// About round trip that completes (main and this branch alike).
    static let aboutTimeout: TimeInterval = 30

    func openAbout() {
        reader.openRendererMenu()
        let about = app.descendants(matching: .any).matching(identifier: ReaderDriver.Identifier.about).firstMatch
        XCTAssertTrue(about.waitForExistence(timeout: Self.aboutTimeout), "About This Build… missing from the menu")
        about.tap()
        XCTAssertTrue(app.staticTexts[ReaderDriver.Identifier.buildVersion].waitForExistence(timeout: Self.aboutTimeout),
                      "About This Build did not open")
    }

    func closeAbout() {
        let done = app.buttons[ReaderDriver.Identifier.buildDone]
        XCTAssertTrue(done.waitForExistence(timeout: Self.aboutTimeout), "Done button missing")
        done.tap()
        XCTAssertTrue(reader.waitForDisappearance(
            of: app.staticTexts[ReaderDriver.Identifier.buildVersion], timeout: Self.aboutTimeout
        ), "About sheet did not dismiss")
        pause(0.5)
    }

    /// The probe's four fields (opens and closes About). Fails, naming the
    /// hook, when the demo has no `-interactionProbe`.
    func readProbe() -> ListUIProbe? {
        openAbout()
        defer { closeAbout() }
        let dispatches = app.staticTexts[ListUIProbe.Identifier.taskDispatches]
        let opens = app.staticTexts[ListUIProbe.Identifier.urlOpens]
        // The probe section is About's last; its rows can sit below the
        // sheet's fold (a list row only exists in the tree once on screen).
        var swipes = 0
        while !(dispatches.exists && opens.exists), swipes < 3 {
            app.swipeUp()
            pause(0.5)
            swipes += 1
        }
        guard dispatches.waitForExistence(timeout: 5), opens.waitForExistence(timeout: 5) else {
            XCTFail("About This Build has no \(ListUIProbe.Identifier.taskDispatches): "
                + "the demo's -interactionProbe hook is missing")
            return nil
        }
        pause(0.5)
        func text(_ identifier: String) -> String {
            let field = app.staticTexts[identifier]
            return field.exists ? field.label : ""
        }
        return ListUIProbe(
            taskDispatches: Int(dispatches.label) ?? -1,
            taskLast: text(ListUIProbe.Identifier.taskLast),
            urlOpens: Int(text(ListUIProbe.Identifier.urlOpens)) ?? -1,
            urlLast: text(ListUIProbe.Identifier.urlLast)
        )
    }

    /// One About count (opens and closes About): waits up to 5 s for
    /// `condition` with two agreeing reads. Fails when the field is absent.
    func aboutCount(_ identifier: String, until condition: (Int) -> Bool) -> Int? {
        openAbout()
        defer { closeAbout() }
        guard app.staticTexts[identifier].waitForExistence(timeout: Self.aboutTimeout) else {
            XCTFail("About This Build has no \(identifier)")
            return nil
        }
        return reader.readCount(identifier, until: condition, settled: true)
    }

    // MARK: Search

    /// Opens Find in Page if needed, runs `query` and returns the counter
    /// once the scan has finished ("current / total", or "0").
    func search(_ query: String) -> String {
        let field = app.textFields[ReaderDriver.Identifier.searchField]
        if !field.exists {
            app.buttons["Find in Page"].tap()
        }
        XCTAssertTrue(field.waitForExistence(timeout: 5), "search field missing")
        field.tap()
        if let current = field.value as? String, !current.isEmpty, current != "Find in page" {
            field.typeText(String(repeating: XCUIKeyboardKey.delete.rawValue, count: current.count))
        }
        field.typeText(query + "\n")
        let counter = app.staticTexts[ReaderDriver.Identifier.searchCounter]
        XCTAssertTrue(counter.waitForExistence(timeout: 10), "search counter missing for \(query)")
        pause(1.5)
        return counter.exists ? counter.label : "missing"
    }

    /// The search bar's Done: clears the search and closes the bar.
    func clearSearch() {
        let field = app.textFields[ReaderDriver.Identifier.searchField]
        XCTAssertTrue(field.exists, "no search to clear")
        let row = field.frame
        let done = app.buttons.matching(NSPredicate(format: "label == %@", "Done")).allElementsBoundByIndex
            .first { abs($0.frame.midY - row.midY) < 30 }
        XCTAssertNotNil(done, "the search bar's Done button is missing")
        done?.tap()
        XCTAssertTrue(reader.waitForDisappearance(of: field, timeout: 5), "the search bar did not close")
        pause(1)
    }

    // MARK: Text size and rotation

    /// Text Size popover: `steps` taps on its larger (> 0) or smaller (< 0)
    /// button, then dismissed. `-fontSizeStep 0` keeps it unpersisted.
    func stepTextSize(_ steps: Int) {
        let toggle = app.buttons["Text Size"]
        XCTAssertTrue(toggle.waitForExistence(timeout: 5), "Text Size control missing")
        toggle.tap()
        let button = app.buttons[steps > 0 ? "Increase Text Size" : "Decrease Text Size"]
        XCTAssertTrue(button.waitForExistence(timeout: 5), "Text Size popover did not open")
        for _ in 0 ..< abs(steps) {
            button.tap()
            pause(0.4)
        }
        let dismissRegion = app.otherElements["PopoverDismissRegion"]
        if dismissRegion.exists {
            dismissRegion.tap()
        } else {
            toggle.tap()
        }
        XCTAssertTrue(reader.waitForDisappearance(of: button, timeout: 5), "Text Size popover did not close")
        pause(1)
    }

    /// Rotates the device and waits for the window to follow.
    func rotate(to orientation: UIDeviceOrientation) {
        XCUIDevice.shared.orientation = orientation
        let landscape = orientation.isLandscape
        let deadline = Date().addingTimeInterval(10)
        var frame = app.windows.firstMatch.frame
        while (frame.width > frame.height) != landscape, Date() < deadline {
            pause(0.25)
            frame = app.windows.firstMatch.frame
        }
        XCTAssertEqual(frame.width > frame.height, landscape, "the window did not rotate (\(frame.size))")
        pause(1.5)
    }

    // MARK: Accessibility tree

    /// Every labelled element of the document's accessibility snapshot, in
    /// snapshot order (scroll indicators excluded).
    func accessibilityTree() throws -> [ListUINode] {
        let root = try app.scrollViews.firstMatch.snapshot()
        var nodes: [ListUINode] = []
        func walk(_ node: XCUIElementSnapshot) {
            let label = node.label
            let indicator = label.hasPrefix("Vertical scroll bar") || label.hasPrefix("Horizontal scroll bar")
            if !label.isEmpty, !indicator, node.frame.height > 0 {
                nodes.append(ListUINode(
                    type: node.elementType, label: label, value: (node.value as? String) ?? "",
                    identifier: node.identifier, frame: node.frame
                ))
            }
            for child in node.children {
                walk(child)
            }
        }
        walk(root)
        return nodes
    }

    /// The nodes fully inside the viewport inset by `inset` points (negative
    /// grows it).
    func nodes(_ tree: [ListUINode], inset: CGFloat) -> [ListUINode] {
        let band = reader.viewport.insetBy(dx: 0, dy: inset)
        return tree.filter { $0.frame.minY >= band.minY && $0.frame.maxY <= band.maxY }
    }
}

